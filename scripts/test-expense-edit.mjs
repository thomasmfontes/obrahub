import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
let rows = [{ id_despesa: 'E1', dc_valor_despesa: 125 }], calls = [];
const source = fs.readFileSync('src/services/neon.ts', 'utf8').replace(/const dbUrl =[\s\S]*?;\r?\n/, 'const dbUrl = "validation";\n');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
vm.runInNewContext(code, { exports, console: { error() {} }, require: name => {
  if (name === '@neondatabase/serverless') return { neonConfig: {}, neon: () => ({ query: async (sql, params) => { calls.push({ sql, params }); return rows; } }) };
  if (name === '../utils/reportSharing') return {};
  if (name === '../utils/formatters') return { normalizeDateToInput: value => value || '' };
  throw new Error(name);
} });
const expense = { id_despesa: 'E1', id_relatorio: 'R1', nm_rubrica: 'Descrição revisada', t_icone_identificador: 'bed', dc_valor_despesa: 125, t_comprovante_storage_urls: ['original-a', 'original-b'] };
assert.equal((await exports.saveDespesaRubrica(expense)).id_despesa, 'E1');
assert.ok(calls[0].sql.startsWith('UPDATE'));
assert.ok(calls[0].sql.includes('AND id_relatorio = $7'));
assert.equal(calls[0].params[5], 'E1');
assert.equal(calls[0].params[6], 'R1');
assert.equal(calls[0].params[3], 2);
await exports.saveDespesaRubrica({ ...expense, t_comprovante_storage_urls: [] });
assert.equal(calls[1].params[3], 0);
assert.equal(calls[1].params[4].length, 0);
rows = [];
await assert.rejects(exports.saveDespesaRubrica(expense), /não confirmou/);
rows = [{ id_despesa: 'OTHER' }];
await assert.rejects(exports.saveDespesaRubrica(expense), /não confirmou/);
rows = [{ id_despesa: 'NEW' }];
await exports.saveDespesaRubrica({ ...expense, id_despesa: undefined });
assert.ok(calls.at(-1).sql.startsWith('INSERT'));
console.log('Passed: update existing expense, report-scoped identity, preserved/removed attachments, confirmed updates and new expense insertion.');
