import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const compile = path => ts.transpileModule(fs.readFileSync(path, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const formatters = {}, validation = {};
vm.runInNewContext(compile('src/utils/formatters.ts'), { exports: formatters });
vm.runInNewContext(compile('src/utils/tripValidation.ts'), { exports: validation });
const data = new Map();
const storage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key) };
const create = (localStorage = storage) => {
  const exports = {};
  vm.runInNewContext(compile('src/utils/reportPosition.ts'), { exports, localStorage, require: name => name === './formatters' ? formatters : validation });
  return exports;
};
const report = { nm_documento_protocolo: 'QA-UX07', nm_missionario: 'QA', nm_polo_destino: 'Destino', t_data_saida: '2026-09-01', t_data_retorno: '2026-09-30' };
const identity = { protocolo: report.nm_documento_protocolo };
let api = create();
assert.equal(api.resolveReportPosition(report).step, 'step1');
api.saveReportPosition(identity, { step: 'step2', day: '2026-09-29' });
api = create();
assert.equal(api.resolveReportPosition(report).day, '2026-09-29', 'Position survives a new session');
assert.equal(api.resolveReportPosition(report).step, 'step2');
assert.ok(api.reportResumeLabel(report).includes('29/09/2026'));
assert.equal(api.resolveReportPosition({ ...report, t_data_saida: '2026-09-02', t_data_retorno: '2026-09-15' }).day, '2026-09-02');
assert.equal(api.resolveReportPosition({ ...report, nm_documento_protocolo: 'OTHER' }).step, 'step1');
api.saveReportPosition(identity, { step: 'step3', day: '2026-09-29' });
assert.equal(api.resolveReportPosition(report).step, 'step3');
assert.equal(api.resolveReportPosition({ ...report, nm_missionario: '' }).step, 'step1');
data.set('obrahub_position_v1_QA-UX07', '{invalid');
