import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const compile = file => ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const formatters = {};
vm.runInNewContext(compile('src/utils/formatters.ts'), { exports: formatters });
const exports = {};
vm.runInNewContext(compile('src/utils/agendaReport.ts'), { exports, require: () => formatters });
const { agendaReportFields } = exports;
const event = { id_agenda: 'QA', nm_titulo: 'Viagem QA', t_tipo: 'viagem', nm_responsavel: ' Irmão QA ', nm_local: ' Destino QA ', t_data_inicio: '2026-10-01T00:00:00.000Z', t_data_fim: '2026-10-04', nr_participantes_esperados: 7, t_observacao: ' Visitar as congregações. ', t_status: 'confirmado' };
const before = JSON.stringify(event);
const fields = agendaReportFields(event);
assert.equal(fields.missionario, 'Irmão QA');
assert.equal(fields.poloDestino, 'Destino QA');
assert.equal(fields.dataSaida, '2026-10-01');
assert.equal(fields.dataRetorno, '2026-10-04');
assert.equal(fields.comitivaCount, 7);
assert.equal(fields.objetivoPrimario, 'Visitar as congregações.');
fields.missionario = 'Outro irmão';
assert.equal(JSON.stringify(event), before, 'Editing the report must not modify the agenda event');
const missing = agendaReportFields({ ...event, nm_responsavel: '', nm_local: '', t_data_inicio: '', t_data_fim: undefined, nr_participantes_esperados: undefined, t_observacao: undefined });
assert.equal(missing.missionario, '');
assert.equal(missing.poloDestino, '');
assert.equal(missing.dataSaida, '');
assert.equal(missing.dataRetorno, '');
assert.equal(missing.objetivoPrimario, '');
assert.equal(missing.comitivaCount, 1);
assert.equal(missing.source.missingParticipants, true);
for (const count of [0, -1, 1.5, NaN]) assert.equal(agendaReportFields({ ...event, nr_participantes_esperados: count }).source.missingParticipants, true);
assert.equal(agendaReportFields({ ...event, t_data_fim: undefined }).dataRetorno, '', 'Missing return date must not be inferred');
assert.equal(agendaReportFields({ ...event, t_observacao: 'a'.repeat(600) }).objetivoPrimario.length, 600, 'Do not truncate agenda observations');
console.log('Passed: selected event fields, dates, participants, missing data, complete observations and independent edits.');
