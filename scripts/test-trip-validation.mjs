import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const source = fs.readFileSync('src/utils/tripValidation.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { validateTrip } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const empty = { missionario: '', poloDestino: '', dataSaida: '', dataRetorno: '' };
assert.deepEqual(Object.keys(validateTrip(empty)), Object.keys(empty));
const complete = { missionario: 'QA', poloDestino: 'Destino', dataSaida: '2026-09-30', dataRetorno: '2026-09-30' };
assert.deepEqual(validateTrip(complete), {}, 'One-day trips are valid');
assert.ok(validateTrip({ ...complete, dataRetorno: '2026-09-29' }).dataRetorno);
assert.ok(validateTrip({ ...complete, dataSaida: '2026-02-30' }).dataSaida);
assert.ok(validateTrip({ ...complete, missionario: '  ' }).missionario);
assert.deepEqual(validateTrip({ ...complete, dataSaida: '2024-02-29', dataRetorno: '2024-03-01' }), {});
let parameters;
const serviceSource = fs.readFileSync('src/services/neon.ts', 'utf8').replace(/const dbUrl =[\s\S]*?;\r?\n/, 'const dbUrl = "validation";\n');
const serviceCode = ts.transpileModule(serviceSource, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exports = {};
vm.runInNewContext(serviceCode, { exports, console, localStorage: { setItem() {} }, require: name => {
  if (name === '@neondatabase/serverless') return { neonConfig: {}, neon: () => ({ query: async (_, params) => { parameters = params; return [{ id_relatorio: 'QA' }]; } }) };
  if (name === '../utils/formatters') return { normalizeDateToInput: value => value || '' };
  if (name === '../utils/reportSharing') return {};
  throw new Error(name);
} });
await exports.saveRelatorioBasico({ nm_documento_protocolo: 'QA', nm_missionario: '', nm_polo_destino: '', t_data_saida: '', t_data_retorno: '', t_objetivo_primario: '' });
assert.equal(parameters[1], '');
assert.equal(parameters[2], '');
assert.equal(parameters[4], null);
assert.equal(parameters[5], null);
assert.equal(parameters[7], '');
console.log('Passed: required fields, real dates, one-day trips, date order and incomplete drafts without fabricated values. No database writes.');
